/**
 * ERP UI platform: deterministic direct HeroUI import inventory.
 *
 * Usage:
 *   pnpm exec tsx scripts/ui/heroui-inventory.ts
 *   pnpm exec tsx scripts/ui/heroui-inventory.ts --format json
 *   pnpm exec tsx scripts/ui/heroui-inventory.ts --format markdown
 *   pnpm exec tsx scripts/ui/heroui-inventory.ts --output docs/ui/inventory.md
 *
 * No external framework dependencies: TypeScript's AST handles aliased/multiline
 * imports, type-only imports and string literals without false positive comments.
 * This script is read-only unless --output is supplied.
 */
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

export type Inventory = {
  schemaVersion: 1;
  directImportFiles: number;
  directImportDeclarations: number;
  directImportingModules: number;
  componentUses: Record<string, number>;
  modules: Record<string, { files: number; declarations: number; componentUses: Record<string, number> }>;
  files: { path: string; module: string; declarations: number; imports: string[] }[];
};

function listFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listFiles(full);
      return entry.isFile() && /\.(?:ts|tsx|mts|cts)$/.test(entry.name) && !/\.d\.ts$/.test(entry.name)
        ? [full]
        : [];
    });
}

export function collectInventory(root: string): Inventory {
  const modulesDir = path.join(root, "src/modules");
  const inventory: Inventory = {
    schemaVersion: 1,
    directImportFiles: 0,
    directImportDeclarations: 0,
    directImportingModules: 0,
    componentUses: {},
    modules: {},
    files: [],
  };

  for (const file of listFiles(modulesDir)) {
    const relativePath = path.relative(root, file).split(path.sep).join("/");
    const module = relativePath.split("/")[2];
    const text = fs.readFileSync(file, "utf8");
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, file.endsWith("tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
    let declarations = 0;
    const names: string[] = [];
    for (const statement of source.statements) {
      if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)
          || statement.moduleSpecifier.text !== "@heroui/react") continue;
      declarations += 1;
      const clause = statement.importClause;
      if (!clause) {
        names.push("(side-effect)");
      } else {
        if (clause.name) names.push("default");
        const bindings = clause.namedBindings;
        if (bindings && ts.isNamespaceImport(bindings)) names.push("*");
        if (bindings && ts.isNamedImports(bindings)) {
          for (const item of bindings.elements) names.push(item.propertyName?.text ?? item.name.text);
        }
        if (!clause.name && !bindings) names.push("(empty)");
      }
    }
    if (!declarations) continue;
    inventory.directImportFiles += 1;
    inventory.directImportDeclarations += declarations;
    const stats = inventory.modules[module] ?? { files: 0, declarations: 0, componentUses: {} };
    stats.files++;
    stats.declarations += declarations;
    inventory.modules[module] = stats;
    for (const name of names) {
      inventory.componentUses[name] = (inventory.componentUses[name] ?? 0) + 1;
      stats.componentUses[name] = (stats.componentUses[name] ?? 0) + 1;
    }
    inventory.files.push({ path: relativePath, module, declarations, imports: names.sort() });
  }
  inventory.directImportingModules = Object.keys(inventory.modules).length;
  inventory.componentUses = sortCountMap(inventory.componentUses);
  inventory.modules = Object.fromEntries(Object.entries(inventory.modules)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, value]) => [name, { ...value, componentUses: sortCountMap(value.componentUses) }]));
  inventory.files.sort((a, b) => a.path.localeCompare(b.path));
  return inventory;
}

function sortCountMap(obj: Record<string, number>): Record<string, number> {
  return Object.fromEntries(Object.entries(obj).sort(([a, av], [b, bv]) => bv - av || a.localeCompare(b)));
}

export function toMarkdown(inventory: Inventory): string {
  const lines = [
    "# Direct HeroUI module imports — inventory",
    "",
    "Generated by \u0060pnpm exec tsx scripts/ui/heroui-inventory.ts --format markdown\u0060. Counts cover \u0060src/modules/**\u0060 only.",
    "",
    "| Metric | Count |",
    "| --- | ---: |",
    `| Files containing direct imports | ${inventory.directImportFiles} |`,
    `| Direct import declarations | ${inventory.directImportDeclarations} |`,
    `| Modules containing direct imports | ${inventory.directImportingModules} |`,
    "",
    "## Modules",
    "",
    "| Module | Files | Import declarations |",
    "| --- | ---: | ---: |",
    ...Object.entries(inventory.modules).sort((a,b) => b[1].files - a[1].files || a[0].localeCompare(b[0]))
      .map(([name, data]) => `| ${name} | ${data.files} | ${data.declarations} |`),
    "",
    "## Imported symbols (named import occurrences)",
    "",
    "| Symbol | Occurrences |",
    "| --- | ---: |",
    ...Object.entries(inventory.componentUses).map(([name, count]) => `| \`${name}\` | ${count} |`),
    "",
    "## Files",
    "",
    "| Path | Imported symbols |",
    "| --- | --- |",
    ...inventory.files.map((file) => `| \`${file.path}\` | ${file.imports.map((i) => "`" + i + "`").join(", ")} |`),
    "",
  ];
  return lines.join("\n");
}

function main() {
  const args = process.argv.slice(2);
  let format: "json" | "markdown" = "markdown";
  let output: string | undefined;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--format" && (args[i + 1] === "json" || args[i + 1] === "markdown")) {
      format = args[++i] as "json" | "markdown";
    } else if (args[i] === "--output" && args[i + 1]) {
      output = args[++i];
    } else {
      throw new Error(`Unknown or incomplete argument: ${args[i]}`);
    }
  }
  const inventory = collectInventory(process.cwd());
  const result = format === "json" ? JSON.stringify(inventory, null, 2) + "\n" : toMarkdown(inventory);
  if (output) {
    const target = path.resolve(process.cwd(), output);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, result);
  } else {
    process.stdout.write(result);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) main();
