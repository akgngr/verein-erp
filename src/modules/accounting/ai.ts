import "server-only";

import { z } from "zod";

import { YEAR_INPUT, aiTool, defineModuleAi, euros, yearSchema } from "@/shared/ai/define";
import { can } from "@/shared/permissions/define";

import { accountingPermissions } from "./permissions";
import { getIncomeExpenseReport, listAccountBalances } from "./server";
import { listTaxRows } from "./queries/tax-reports";
import { listOpenItems } from "./queries/invoices";
import { AGING_BUCKETS } from "./services/invoice-payments";
import { berlinToday } from "./utils";
import { getTaxSettings } from "./services/tax";
import { computeEuer, computeUstva, vatPeriods } from "./services/tax-reports";
import { getDb } from "@/shared/db";

/** Muhasebe: yalnızca toplamlar ve hazır rapor bağlantıları. Sözleşme: src/shared/ai/define.ts. */
export const ai = defineModuleAi({
  module: "accounting",
  tools: [
    aiTool({
      name: "get_accounting_summary",
      operation: "read",
      allowed: (user) => can(user.role, accountingPermissions, "view"),
      description:
        "Income/expense summary for a fiscal year: actual, planned and previous-year amounts (EUR) per category and tax sphere, plus account balances. Contains no personal data.",
      schema: yearSchema,
      inputSchema: YEAR_INPUT,
      run: async ({ year }) => {
        const [report, balances] = await Promise.all([getIncomeExpenseReport(year), listAccountBalances()]);
        return {
          year,
          categories: report.rows
            .filter((row) => row.categoryId)
            .map((row) => ({
              category: row.categoryName,
              sphere: row.sphere,
              direction: row.direction,
              actualEur: euros(row.actualCents),
              planEur: euros(row.planCents),
              previousYearEur: euros(row.previousYearCents),
            })),
          economicOperationNotice: report.economicOperationNotice,
          accounts: balances.filter((account) => account.isActive).map((account) => ({ account: account.name, type: account.type, balanceEur: euros(account.balanceCents) })),
        };
      },
    }),
    aiTool({
      name: "get_vat_summary",
      operation: "read",
      allowed: (user) => can(user.role, accountingPermissions, "view"),
      description:
        "VAT (Umsatzsteuer) overview for a year: UStVA key figures per filing period (Kz 81/86 tax bases, Kz 66 input tax, Kz 83 payable/refund) and a simplified EÜR result. Totals only, no personal data. Not a tax filing; the user must verify and submit via Elster.",
      schema: yearSchema,
      inputSchema: YEAR_INPUT,
      run: async ({ year }) => {
        const settings = await getTaxSettings(getDb());
        const rows = await listTaxRows(new Date(Date.UTC(year, 0, 1)), new Date(Date.UTC(year, 11, 31)));
        const periods = vatPeriods(year, settings.vatPeriod).map((period) => {
          const result = computeUstva(rows.filter((row) => row.bookingDate >= period.from && row.bookingDate <= period.to));
          return { period: period.key, kz81BaseEur: result.kz81BaseEuros, kz86BaseEur: result.kz86BaseEuros, kz66Eur: euros(result.kz66Cents), kz83Eur: euros(result.kz83Cents) };
        });
        const euer = computeEuer(rows);
        return {
          year,
          chartOfAccounts: settings.chartOfAccounts,
          smallBusiness: settings.smallBusiness,
          taxMethod: settings.taxMethod,
          periods,
          euer: { incomeNetEur: euros(euer.incomeNetCents), outputTaxEur: euros(euer.outputTaxCents), expenseNetEur: euros(euer.expenseNetCents), inputTaxEur: euros(euer.inputTaxCents), resultEur: euros(euer.resultCents) },
          page: `/muhasebe/vergi?yil=${year}`,
        };
      },
    }),
    aiTool({
      name: "get_open_items_summary",
      operation: "read",
      allowed: (user) => can(user.role, accountingPermissions, "view"),
      description:
        "Accounts receivable (open invoices / OPOS) aging summary: count and open amount (EUR) per aging bucket (not due, 1-30, 31-60, 61-90, >90 days overdue). Totals only — no customer names or invoice details.",
      schema: z.object({}),
      inputSchema: { type: "object", properties: {}, additionalProperties: false },
      run: async () => {
        const rows = await listOpenItems(berlinToday());
        return {
          buckets: AGING_BUCKETS.map((bucket) => {
            const items = rows.filter((row) => row.bucket === bucket);
            return { bucket, count: items.length, openEur: euros(items.reduce((sum, row) => sum + row.openCents, 0)) };
          }),
          totalOpenEur: euros(rows.reduce((sum, row) => sum + row.openCents, 0)),
          page: "/muhasebe/faturalar?gorunum=opos",
        };
      },
    }),
    aiTool({
      name: "get_report_link",
      operation: "read",
      allowed: (user) => can(user.role, accountingPermissions, "view"),
      description:
        "Returns a download link for a ready-made report (generated by the system with the user's own permissions; its content never reaches you). Give the link to the user as a markdown link.",
      schema: z.object({ report: z.enum(["income_expense_pdf", "income_expense_excel", "annual_report_pdf", "datev_bookings"]), year: z.number().int().min(2000).max(2100) }),
      inputSchema: {
        type: "object",
        properties: {
          report: {
            type: "string",
            enum: ["income_expense_pdf", "income_expense_excel", "annual_report_pdf", "datev_bookings"],
            description: "income_expense_pdf: income/expense list (PDF); income_expense_excel: same list (Excel); annual_report_pdf: annual treasurer report (Kassenbericht); datev_bookings: DATEV EXTF booking batch for the tax advisor", // i18n-ignore (model-facing tool text)
          },
          year: { type: "integer" },
        },
        required: ["report", "year"],
        additionalProperties: false,
      },
      run: async ({ report, year }) => {
        const url = {
          income_expense_pdf: `/api/accounting/export/pdf?year=${year}`,
          income_expense_excel: `/api/accounting/export?year=${year}`,
          annual_report_pdf: `/api/accounting/reports/annual/pdf?year=${year}`,
          datev_bookings: `/api/accounting/datev?kind=bookings&from=${year}-01-01&to=${year}-12-31`,
        }[report];
        return { url, note: "Give this link to the user; it opens in their browser with their own session." };
      },
    }),
  ],
  actions: {},
});
